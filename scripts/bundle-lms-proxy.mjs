/**
 * Joins the lms-proxy Edge Function and its shared helpers (supabase/functions/_shared/lms.ts)
 * into one file, supabase/functions/lms-proxy/DASHBOARD_PASTE.ts, so it can be pasted into the
 * Supabase dashboard editor (Edge Functions → Deploy a new function → Via Editor).
 * Run: npm run lms:bundle
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const fnDir = join(import.meta.dirname, '..', 'supabase', 'functions');
const index = readFileSync(join(fnDir, 'lms-proxy', 'index.ts'), 'utf8');
const shared = readFileSync(join(fnDir, '_shared', 'lms.ts'), 'utf8');

const importLine = /^import \{[^}]+\} from '\.\.\/_shared\/lms\.ts';\n/m;
if (!importLine.test(index)) throw new Error('lms-proxy/index.ts no longer imports ../_shared/lms.ts the expected way');

const header = `// =============================================================================
// GENERATED by scripts/bundle-lms-proxy.mjs — do not edit; edit lms-proxy/index.ts and
// _shared/lms.ts, then run \`npm run lms:bundle\`.
// Paste this whole file into Supabase → Edge Functions → Deploy a new function → Via Editor,
// function name: lms-proxy
// =============================================================================
`;

const body = index.replace(importLine, '') + '\n// ---- shared LMS helpers (supabase/functions/_shared/lms.ts) ----\n' + shared;
writeFileSync(join(fnDir, 'lms-proxy', 'DASHBOARD_PASTE.ts'), header + body);
console.log('Wrote supabase/functions/lms-proxy/DASHBOARD_PASTE.ts');
